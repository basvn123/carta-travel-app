const VETO = new Set(FILES);

/** The file name inside a photograph's URL: the Commons file of a thumb or
 *  original, else the last path segment (a Geograph photo), or ''. */
export function commonsFile(url) {
  const s = String(url || '').split(/[?#]/)[0];
  const thumb = s.match(/\/commons\/thumb\/[0-9a-f]\/[0-9a-f]{2}\/([^/]+)\//);
  if (thumb) return thumb[1];
  const orig = s.match(/\/commons\/[0-9a-f]\/[0-9a-f]{2}\/([^/]+)$/);
  if (orig) return orig[1];
  return s.slice(s.lastIndexOf('/') + 1);
}

/** True when this photograph was looked at and refused. */
export function vetoed(url) {
  return VETO.size > 0 && VETO.has(commonsFile(url));
}

/** The URL, or null when it is refused. */
export function okPhoto(url) {
  return url && !vetoed(url) ? url : null;
}

/** The first image of a layer row's gallery ({u}) that is not refused. */
export function firstOkImage(images) {
  return (Array.isArray(images) ? images : []).find((im) => im?.u && !vetoed(im.u)) || null;
}
