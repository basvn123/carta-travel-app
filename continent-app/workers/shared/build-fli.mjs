// Rebuilds fli.bundle.mjs from the vendored fli-js source (workers/shared/fli).
// Run from continent-app/: node workers/shared/build-fli.mjs
// Needs esbuild through npx; the bundle is committed, so the app, the Pages
// Function, the sweep Worker and the node tests never need a build step.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = `${here}fli.bundle.mjs`;
execSync([
  'npx --yes esbuild@0.25.10', `"${here}fli/entry.ts"`, '--bundle', '--format=esm',
  '--platform=neutral', '--main-fields=module,main', '--minify-syntax', '--minify-whitespace',
  '--external:node:buffer', '--legal-comments=inline', `"--outfile=${out}"`,
].join(' '), { stdio: 'inherit' });
const banner = '// Generated by workers/shared/build-fli.mjs from fli-js (MIT, Punit Arani,\n'
  + '// see fli/LICENSE). Do not edit by hand.\n';
writeFileSync(out, banner + readFileSync(out, 'utf8'));
