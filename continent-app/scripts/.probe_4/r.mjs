import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:1440,height:900}, serviceWorkers:'block'})).newPage();
await p.addInitScript(()=>{localStorage.setItem('continent.lang.v1','en');localStorage.setItem('continent.guestMode.v1','1');localStorage.setItem('continent.homeSeen.v1','1');});
await p.goto('http://localhost:4173/?tab=plan');
await p.locator('.pf-open-start').click();
await p.waitForTimeout(2500);
console.log(await p.locator('.header-nav-item').first().isVisible(), p.url());
await p.screenshot({path:'/tmp/claude-0/r.png'});
await b.close();
