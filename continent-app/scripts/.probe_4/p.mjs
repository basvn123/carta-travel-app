import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const wire = JSON.parse(readFileSync('public/trails/AL.json','utf8'));
const hikes = wire.trips.filter(t=>t.category!=='citytrip');
const loop = hikes.find(t=>t.id===63433);
console.log(loop.id, wire.trips.length, hikes.length);
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:+process.argv[2]||1280,height:900}, serviceWorkers:'block', acceptDownloads:true})).newPage();
await p.addInitScript(()=>{localStorage.setItem('continent.lang.v1','en');localStorage.setItem('continent.guestMode.v1','1');localStorage.setItem('continent.homeSeen.v1','1');localStorage.setItem('carta.mapGuideDone','1');});
await p.goto('http://localhost:4173/#trail='+loop.id+'&tc=AL');
await p.waitForTimeout(9000);
await p.screenshot({path:'/tmp/claude-0/pp.png'});
console.log(await p.evaluate(()=>[...document.querySelectorAll('.pt-head *')].map(e=>e.className+'|'+e.textContent.trim().slice(0,80)).join('\n')));
await b.close();
