import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:1500,height:950}, serviceWorkers:'block'})).newPage();
await p.addInitScript(()=>{localStorage.setItem('continent.lang.v1','en');localStorage.setItem('continent.guestMode.v1','1');localStorage.setItem('continent.homeSeen.v1','1');localStorage.setItem('carta.welcomeSeen','1');localStorage.setItem('carta.fareNoticeSeen','1');});
await p.goto('http://localhost:4173/?tab=explore#dest=SZG');
await p.getByRole('button',{name:/plan a trip/i}).first().click({timeout:30000});
await p.waitForTimeout(3000);
await p.getByRole('button',{name:/^Germany, from/}).click();
await p.waitForTimeout(800);
console.log('NEXT', await p.evaluate(()=>[...document.querySelectorAll('button')].filter(e=>e.offsetParent&&/next|continue|guide-next|stay/i.test(e.className+e.textContent)).map(b=>b.className+'|'+b.textContent.trim().slice(0,30)).join('\n')));
await p.locator('.guide-next').first().click({timeout:5000}).catch(e=>console.log('nonext'));
await p.waitForTimeout(3000);
await p.screenshot({path:'/tmp/claude-0/u.png'});
console.log(await p.evaluate(()=>[...document.querySelectorAll('main a,main button,main h1,main h2,main h3,main input')].filter(e=>e.offsetParent).map(b=>b.tagName+'.'+String(b.className).slice(0,45)+'|'+(b.getAttribute('aria-label')||b.textContent).trim().slice(0,40)).filter(l=>!/pf-rail|cal-day/.test(l)).slice(0,40).join('\n')));
await b.close();
