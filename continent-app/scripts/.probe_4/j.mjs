import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:1440,height:950}, serviceWorkers:'block'})).newPage();
await p.addInitScript(()=>{localStorage.setItem('continent.lang.v1','en');localStorage.setItem('continent.guestMode.v1','1');localStorage.setItem('continent.homeSeen.v1','1');localStorage.setItem('carta.welcomeSeen','1');});
await p.goto('http://localhost:4173/?tab=explore&cat=trips');
await p.waitForTimeout(4000);
await p.locator('.card-open:visible').first().click();
await p.waitForTimeout(3000);
console.log(p.url());
console.log(await p.evaluate(()=>[...document.querySelectorAll('main h1,main h2,main h3,main .card-open,main [class*=seg-item],main select,main [class*=chip]')].filter(e=>e.getClientRects().length).slice(0,30).map(e=>e.tagName+'.'+e.className+'|'+(e.getAttribute('href')||'')+'|'+e.textContent.trim().slice(0,30)).join('\n')));
await b.close();
