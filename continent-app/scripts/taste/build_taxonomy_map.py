"""Write continent-app/src/lib/taste/taxonomyMap.js from the taxonomy (T1152, ROADMAP F3).

The taste profile in the app maps a traveller's saves, trips and filters onto
the Carta travel taxonomy (pipeline/taxonomy/carta_taxonomy.yaml, T1149). The
app cannot read YAML, so this writes the part it needs as a plain module:
the mapping rows of the vocabularies the app's signals use, and every node
those rows reach (with its ancestors), with facet, parent, level and labels.

    python -I continent-app/scripts/taste/build_taxonomy_map.py          # write
    python -I continent-app/scripts/taste/build_taxonomy_map.py --check  # exit 1 when stale

tests/tasteProfile.test.mjs runs --check, so a taxonomy or mapping change
that is not carried into the app fails npm test.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
TAX = ROOT / "pipeline" / "taxonomy" / "carta_taxonomy.yaml"
MAP = ROOT / "pipeline" / "taxonomy" / "mapping.yaml"
OUT = ROOT / "continent-app" / "src" / "lib" / "taste" / "taxonomyMap.js"

# mapping.yaml source -> the name the app module uses for it
SOURCES = {
    "place.categories": "categories",
    "place.tags": "tags",
    "likes": "likes",
    "explore.trip_kinds": "tripKinds",
}
# A saved trail, beach, lake, mountain or cycle route says one thing by its kind.
FAV_KINDS = {
    "trail": ["act.hiking"],
    "beach": ["set.beach"],
    "lake": ["set.lake"],
    "mountain": ["set.mountains"],
    "cycle": ["act.cycling"],
}
LANGS = ("en", "de", "fr", "es", "it", "nl")


def build() -> str:
    tax = yaml.safe_load(TAX.read_text(encoding="utf-8"))
    mapping = yaml.safe_load(MAP.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in tax["nodes"]}
    sources = {}
    used = set()
    for src, name in SOURCES.items():
        rows = mapping["sources"][src]["map"]
        sources[name] = {str(k): list(v) for k, v in sorted(rows.items(), key=lambda kv: str(kv[0])) if v}
        for ids in sources[name].values():
            used.update(ids)
    for ids in FAV_KINDS.values():
        used.update(ids)
    missing = sorted(i for i in used if i not in nodes)
    if missing:
        raise SystemExit(f"nodes not in the taxonomy: {missing}")
    keep = set()
    for i in used:
        while i and i not in keep:
            keep.add(i)
            i = nodes[i].get("parent")
    out_nodes = {}
    for i in sorted(keep):
        n = nodes[i]
        label = {lang: (n.get("label") or {}).get(lang) for lang in LANGS}
        out_nodes[i] = {
            "facet": n["facet"],
            "level": n["level"],
            "parent": n.get("parent"),
            "label": {k: v for k, v in label.items() if v},
        }
    body = {
        "version": tax["version"],
        "nodes": out_nodes,
        "sources": sources,
        "favKinds": FAV_KINDS,
    }
    js = json.dumps(body, ensure_ascii=False, indent=1, sort_keys=True)
    return (
        "// Generated by continent-app/scripts/taste/build_taxonomy_map.py from\n"
        "// pipeline/taxonomy/carta_taxonomy.yaml and mapping.yaml (T1152). Do not edit.\n"
        f"export const TAXONOMY = Object.freeze({js});\n"
    )


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run the script without --check")
            return 1
        print("taxonomy map is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
