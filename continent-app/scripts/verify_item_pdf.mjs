// verify_item_pdf.mjs (T430, T431): the Download PDF of an item page and of a
// trip page produce a real file in Carta's own face, with the page's words.
//
//   CARTA_PORT=5298 node scripts/verify_item_pdf.mjs
//
// For each page it presses "Download PDF", saves the download, and reads the
// file with python's pypdf (pip install pypdf): the embedded fonts are
// Figtree, the page count is sane, the title and the credits line are in the
// text, and no em dash, en dash or middot made it onto the paper.
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const BASE = `http://localhost:${process.env.CARTA_PORT || 4173}/`;
const OUT = mkdtempSync(join(tmpdir(), 'carta-pdf-'));
const PAGES = [
  { name: 'mountain', hash: '#mtn=mk-mount-korab-Q912579&mc=MK', cat: 'mountains', title: /Korab/, minPages: 1 },
  { name: 'trail', hash: '#trail=20050&tc=AT', cat: 'trails', title: null, minPages: 1 },
  { name: 'trip', hash: '#journey=ad-hiking-coma-pedrosa-madriu', cat: 'trips', title: /Andorra High Route/, minPages: 3 },
  { name: 'sample', hash: '#journey=es-pilgrim-camino-sarria-santiago', cat: 'trips', title: /Camino/, minPages: 3 },
];

const checks = [];
const check = (label, ok, note = '') => checks.push({ label, ok: Boolean(ok), note });

const READ = `
import sys, json
from pypdf import PdfReader
r = PdfReader(sys.argv[1])
fonts = set()
figtree = set()
for p in r.pages:
    res = p.get('/Resources') or {}
    fd = res.get('/Font')
    if fd is None:
        continue
    fd = fd.get_object()
    for k in fd:
        ref = fd.raw_get(k)
        f = ref.get_object()
        name = str(f.get('/BaseFont'))
        fonts.add(name)
        # jsPDF embeds a TTF as a Type0 font whose descendant carries the file.
        for d in (f.get('/DescendantFonts') or []):
            desc = d.get_object().get('/FontDescriptor')
            if 'Figtree' in name and desc is not None and '/FontFile2' in desc.get_object():
                figtree.add(getattr(ref, 'idnum', k))
text = '\\n'.join((p.extract_text() or '') for p in r.pages)
print(json.dumps({'pages': len(r.pages), 'fonts': sorted(fonts), 'figtree': len(figtree), 'text': text}))
`;

const browser = await chromium.launch();
for (const pg of PAGES) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  await page.addInitScript((cat) => {
    for (const [k, v] of [['continent.lang.v1', 'en'], ['continent.guestMode.v1', '1'], ['continent.homeSeen.v1', '1'],
      ['continent.mapGuideDismissed.v1', '1'], ['carta.welcomeSeen.v1', '1'],
      ['carta.places.v1', JSON.stringify({ cat, country: '', near: null })]]) localStorage.setItem(k, v);
  }, pg.cat);
  await page.goto(`${BASE}?tab=places${pg.hash}`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  const ok = await page.waitForSelector('.tpage h1', { timeout: 60000 }).then(() => true, () => false);
  check(`${pg.name}: the page opens`, ok);
  if (!ok) { await page.close(); continue; }
  await page.waitForTimeout(2500);
  const btn = page.locator('.ipage-pdf').first();
  check(`${pg.name}: one Download PDF door`, await page.locator('.ipage-pdf').count() === 1);
  try {
    await btn.scrollIntoViewIfNeeded();
    const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 90000 }), btn.click()]);
    const file = join(OUT, `${pg.name}.pdf`);
    await dl.saveAs(file);
    const info = JSON.parse(execFileSync('python3', ['-c', READ, file], { encoding: 'utf8', maxBuffer: 64 << 20 }));
    check(`${pg.name}: a PDF downloads`, info.pages >= pg.minPages, `${info.pages} pages, ${dl.suggestedFilename()}`);
    // jsPDF lists its fourteen built-in faces whether or not a page uses
    // them; the page's own text is set in the embedded Figtree weights.
    check(`${pg.name}: set in Figtree, two weights or more embedded`, info.figtree >= 2, `${info.figtree} Figtree fonts embedded`);
    if (pg.title) check(`${pg.name}: the title is on the paper`, pg.title.test(info.text));
    check(`${pg.name}: the credits close it`, /Generated by Carta/.test(info.text));
    check(`${pg.name}: no em dash, en dash or middot`, !/[—–·]/.test(info.text));
  } catch (e) {
    check(`${pg.name}: a PDF downloads`, false, String(e.message || e).split('\n')[0]);
  }
  await page.close();
}
await browser.close();

let bad = 0;
for (const c of checks) {
  if (!c.ok) bad += 1;
  console.log(`${c.ok ? 'ok  ' : 'FAIL'}  ${c.label}${c.note ? `  (${c.note})` : ''}`);
}
console.log(`\n${checks.length - bad}/${checks.length} checks passed  (files in ${OUT})`);
process.exit(bad ? 1 : 0);
