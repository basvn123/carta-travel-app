import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.addInitScript(()=>{for (const k of ['continent.guestMode.v1','continent.homeSeen.v1','carta.fareNoticeSeen','carta.welcomeSeen','carta.onboardSeen']) localStorage.setItem(k,'1')});
await p.goto('http://localhost:4173/?o=CRL&tab=map&st=hotel5', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(5000);
await p.getByRole('link', { name: 'Account & preferences' }).first().click();
await p.waitForTimeout(2500);
console.log(p.url().slice(0,60), await p.evaluate(()=>[...document.querySelectorAll('.account-panel, main, .app-main, body')].map(e=>e.className+'|'+e.innerText.slice(0,400))));
await b.close();
