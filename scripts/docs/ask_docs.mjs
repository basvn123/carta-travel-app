#!/usr/bin/env node
/*
 * Ask the docs (T1168, ROADMAP B8): the CLI and the index builder.
 *
 *   node scripts/docs/ask_docs.mjs build [--out docs/assets/ask-docs/index.js]   write the passages the docs site search box loads
 *   node scripts/docs/ask_docs.mjs "how is the price confidence computed?" [--model]
 *   node scripts/docs/ask_docs.mjs --stats
 *
 * The default answer is extractive and needs no model. --model rewrites it
 * through the AI gateway (feature ask: Workers AI chain, config in
 * continent-app/functions/_lib/aiModels.js; the prompt is prompts/ask-docs),
 * never the Claude API; the rewrite is dropped for the extractive text when it
 * fails the grounding check or the gateway is unreachable.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
export const core = require('./ask_docs_core.js');
export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SKIP = /\.(csv|json)$|^tos\//;

export function listDocs(dir = join(ROOT, 'docs')) {
  const out = [];
  const walk = (d) => {
    for (const f of readdirSync(d).sort()) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (f.endsWith('.md') && !SKIP.test(relative(dir, p).replace(/\\/g, '/'))) out.push(p);
    }
  };
  walk(dir);
  return out;
}

export function loadPassages(dir = join(ROOT, 'docs')) {
  const all = [];
  for (const p of listDocs(dir)) {
    const rel = relative(dir, p).replace(/\\/g, '/');
    all.push(...core.chunkMarkdown(rel, readFileSync(p, 'utf8')));
  }
  return all;
}

export const buildDocsIndex = (dir) => core.buildIndex(loadPassages(dir));

/** The registry prompt for the optional model rewrite. */
export async function modelAnswer(ans, question, env = process.env, callModel = null) {
  const { loadPrompt, frag } = await import('../prompts/lib.mjs');
  const call = callModel || (await import('../../continent-app/functions/_lib/aiModels.js')).callModel;
  const p = loadPrompt('ask-docs');
  const notes = ans.citations.map((c) => `[${c.n}] (${c.label}) ${c.text}`).join('\n\n');
  const r = await call({ feature: 'ask', env, system: frag(p, 'system'), user: `${frag(p, 'user.question')}\n${question}\n\n${frag(p, 'user.notes')}\n${notes}`, temperature: 0 });
  if (!r.ok) return { ok: false, why: r.code || 'gateway' };
  const out = { ...ans, text: r.text.replace(/[–—]/g, '-').trim() };
  const g = core.groundingCheck(out);
  return g.ok ? { ok: true, ans: out } : { ok: false, why: `grounding: ${g.problems[0]}` };
}

function print(a) {
  console.log(a.text);
  for (const c of a.citations) console.log(`  [${c.n}] ${c.label}  (docs/${c.link})`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const arg = (n, d) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
  if (argv[0] === 'build') {
    const passages = loadPassages();
    const out = resolve(ROOT, arg('--out', 'docs/assets/ask-docs/index.js'));
    mkdirSync(dirname(out), { recursive: true });
    const rows = passages.map((p) => ({ id: p.id, path: p.path, title: p.title, head: p.head, anchor: p.anchor, text: p.text }));
    writeFileSync(out, `/* Generated by scripts/docs/ask_docs.mjs build (T1168). Do not edit. */\nwindow.CARTA_DOCS_PASSAGES=${JSON.stringify(rows)};\n`);
    console.log(`${rows.length} passages from ${listDocs().length} files, ${(statSync(out).size / 1024).toFixed(0)} KB, written to ${relative(ROOT, out)}`);
  } else if (argv.includes('--stats')) {
    const p = loadPassages();
    console.log(`${listDocs().length} files, ${p.length} passages, mean ${Math.round(p.reduce((s, x) => s + x.text.length, 0) / p.length)} chars`);
  } else if (argv[0]) {
    const q = argv.filter((a) => !a.startsWith('--')).join(' ');
    const idx = buildDocsIndex();
    let a = core.answer(idx, q);
    if (argv.includes('--model') && !a.abstained) {
      const m = await modelAnswer(a, q);
      if (m.ok) a = m.ans; else console.error(`(model answer dropped: ${m.why}; showing the extractive answer)`);
    }
    print(a);
  } else {
    console.error('usage: ask_docs.mjs "<question>" [--model] | build | --stats');
    process.exit(2);
  }
}
