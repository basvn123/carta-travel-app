"""Reference generators for the Python API and the app library (ROADMAP B6, T1167).

Both read source as text and import nothing: pipeline modules need heavy
dependencies and some do work on import, which is why pdoc (it imports) was not
picked (see the T1167 report, Research).

    python.md   modules of pipeline/ and scripts/: summary, public functions and
                classes with signature and first docstring line (ast)
    app-lib.md  continent-app/src/lib/*.js: file header comment and every
                `export` with the first line of its JSDoc comment
"""
from __future__ import annotations

import ast
import re
import warnings
from pathlib import Path

PY_DIRS = ["pipeline", "scripts", "src"]


def _c(s) -> str:
    return re.sub(r"\s+", " ", str(s or "")).replace("|", "\\|").replace("\u2014", "-").replace("\u2013", "-").strip()


def _sig(fn) -> str:
    try:
        args = ast.unparse(fn.args)
    except Exception:
        args = "..."
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns is not None else ""
    return f"{fn.name}({args}){ret}"


def _first(doc: str | None) -> str:
    return _c((doc or "").strip().split("\n\n")[0])[:240]


def py_modules(root: Path) -> list[Path]:
    out = []
    for d in PY_DIRS:
        base = root / d
        if base.is_dir():
            for p in sorted(base.rglob("*.py")):
                rel = p.relative_to(root).as_posix()
                if "/archive/" in rel or "__pycache__" in rel or p.name.startswith("test_"):
                    continue
                out.append(p)
    rp = root / "run_pipeline.py"
    if rp.is_file():
        out.append(rp)
    return out


def render_python(root: Path) -> str:
    lines = [
        "# Python API reference",
        "",
        "Generated by `python -I scripts/docs/build_reference.py` from the source with `ast` (nothing is imported). Public means a name without a leading underscore. Do not edit by hand (ROADMAP B6, T1167). Task cadence and commands are in [tasks.md](tasks.md).",
        "",
    ]
    mods, nfun, ncls, ndoc = 0, 0, 0, 0
    body = []
    for p in py_modules(root):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                tree = ast.parse(p.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        rel = p.relative_to(root).as_posix()
        items = []
        for n in tree.body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
                items.append(("def", _sig(n), _first(ast.get_docstring(n))))
                nfun += 1
                ndoc += bool(ast.get_docstring(n))
            elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
                items.append(("class", n.name, _first(ast.get_docstring(n))))
                ncls += 1
                ndoc += bool(ast.get_docstring(n))
                for m in n.body:
                    if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("_"):
                        items.append(("method", f"{n.name}.{_sig(m)}", _first(ast.get_docstring(m))))
        mods += 1
        body += ["", f"## `{rel}`", "", _first(ast.get_docstring(tree)) or "_No module docstring._", ""]
        if items:
            body += ["| Kind | Name | Summary |", "|---|---|---|"]
            for k, name, doc in items:
                body.append(f"| {k} | `{_c(name)}` | {doc} |")
    lines.append(f"{mods} modules, {nfun} public functions, {ncls} classes; {ndoc} have a docstring.")
    return "\n".join(lines + body) + "\n"


EXPORT = re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\}", re.M)


def _jsdoc_before(text: str, pos: int) -> str:
    head = text[:pos].rstrip()
    if head.endswith("*/"):
        start = head.rfind("/**")
        if start != -1:
            block = head[start + 3 : -2]
            block = re.sub(r"^\s*\*\s?", "", block, flags=re.M).strip()
            first = block.split("\n\n")[0]
            first = re.split(r"\n\s*@", first)[0]
            return _c(first)[:240]
    lines = head.split("\n")
    out = []
    for ln in reversed(lines):
        if ln.strip().startswith("//"):
            out.append(ln.strip()[2:].strip())
        else:
            break
    return _c(" ".join(reversed(out)))[:240] if out else ""


def _file_header(text: str) -> str:
    out = []
    for ln in text.split("\n"):
        s = ln.strip()
        if s.startswith("//"):
            out.append(s[2:].strip())
        elif s.startswith("/**") or s.startswith("/*") or s.startswith("*"):
            out.append(s.strip("/* ").strip())
        else:
            break
    return _c(" ".join(out))[:300]


def render_app_lib(root: Path) -> str:
    lib = root / "continent-app" / "src" / "lib"
    lines = [
        "# App library reference (continent-app/src/lib)",
        "",
        "Generated by `python -I scripts/docs/build_reference.py` from the source (JSDoc and leading comments, read as text). Do not edit by hand (ROADMAP B6, T1167). The rules and thresholds behind these functions are in `docs/HANDBOOK.md` and `docs/logic/`.",
        "",
    ]
    body, nfile, nexp, ndoc = [], 0, 0, 0
    for p in sorted(lib.rglob("*.js")):
        rel = p.relative_to(root).as_posix()
        if ".test." in p.name or "/__" in rel:
            continue
        text = p.read_text(encoding="utf-8")
        exps = []
        for m in EXPORT.finditer(text):
            d = _jsdoc_before(text, m.start())
            exps.append((m.group(1).replace("function*", "function"), m.group(2), d))
        for m in EXPORT_LIST.finditer(text):
            for nm in m.group(1).split(","):
                nm = nm.strip().split(" as ")[-1].strip()
                if nm:
                    exps.append(("re-export", nm, ""))
        if not exps:
            continue
        nfile += 1
        nexp += len(exps)
        ndoc += sum(1 for e in exps if e[2])
        body += ["", f"## `{rel[len('continent-app/'):]}`", "", _file_header(text) or "_No header comment._", "", "| Kind | Name | Summary |", "|---|---|---|"]
        for k, n, d in exps:
            body.append(f"| {k} | `{n}` | {_c(d)} |")
    lines.append(f"{nfile} modules, {nexp} exports; {ndoc} have a comment above them.")
    return "\n".join(lines + body) + "\n"
