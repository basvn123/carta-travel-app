"""Build and check docs/reference/ (ROADMAP B6, T1167).

    python -I scripts/docs/build_reference.py            # write the generated files
    python -I scripts/docs/build_reference.py --check    # exit 1 when tasks.md, supabase.md or openapi.md is stale
    python -I scripts/docs/build_reference.py --check --strict   # also python.md and app-lib.md

The two API files move with every code edit, so they fail the check only with --strict
(otherwise a note); the task catalogue and the Supabase schema change rarely and fail it.
Writes docs/reference/{python,app-lib,tasks,supabase,openapi}.md. openapi.md renders
services/intelligence/openapi.json (F5, T1154), which `python -m intelligence.openapi_dump`
writes from the FastAPI app; here it is read as text. config.md (config_reference.py,
B4) and evals.md (eval/run.mjs, F6) have their own generators and are only listed here.
Pure text in, text out: no network, no imports of repo code. CARTA_REPO_ROOT points at
another tree.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
ROOT = Path(os.environ.get("CARTA_REPO_ROOT") or HERE.parents[1]).resolve()

import reference_api as api  # noqa: E402
import reference_sql_tasks as st  # noqa: E402

OPENAPI_JSON = "services/intelligence/openapi.json"


def _schema_ref(s: dict) -> str:
    if not isinstance(s, dict):
        return ""
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if s.get("type") == "array":
        return f"list of {_schema_ref(s.get('items') or {})}"
    if "anyOf" in s:
        return " or ".join(_schema_ref(x) for x in s["anyOf"])
    return s.get("type", "")


def _cell(v) -> str:
    return " ".join(str(v).split()).replace("|", "/")


def render_openapi(root: Path) -> str:
    """docs/reference/openapi.md from the Intelligence API's OpenAPI file: operations, then schemas."""
    p = root / OPENAPI_JSON
    if not p.is_file():
        return "# Intelligence API (OpenAPI)\n\nGenerated by `python -I scripts/docs/build_reference.py`. No `openapi.json` yet.\n"
    spec = json.loads(p.read_text(encoding="utf-8"))
    info = spec.get("info") or {}
    out = [
        f"# {info.get('title', 'Intelligence API')} {info.get('version', '')} (OpenAPI)",
        "",
        (f"Generated by `python -I scripts/docs/build_reference.py` from `{OPENAPI_JSON}` "
         "(written by `python -m intelligence.openapi_dump` in `services/intelligence/`). Do not edit by hand. "
         "ROADMAP F5, T1154; README `services/intelligence/README.md`."),
        "",
        _cell(info.get("description", "")),
        "",
        f"OpenAPI {spec.get('openapi', '')}. Security schemes: " + ", ".join(f"`{k}` ({_cell(v.get('type', ''))} {_cell(v.get('name') or v.get('scheme') or '')})"
                    for k, v in sorted((spec.get("components") or {}).get("securitySchemes", {}).items())) + ".",
        "",
        "## Operations",
        "",
        "| Method | Path | Summary | Request | Responses | Key |",
        "|---|---|---|---|---|---|",
    ]
    for path, ops in sorted(spec.get("paths", {}).items()):
        for method, op in sorted(ops.items()):
            body = (((op.get("requestBody") or {}).get("content") or {}).get("application/json") or {}).get("schema") or {}
            params = ", ".join(f"{x['name']} ({x['in']})" for x in op.get("parameters") or [])
            req = " ".join(x for x in (_schema_ref(body), params) if x) or "none"
            resp = ", ".join(sorted(op.get("responses", {})))
            key = "yes" if op.get("security") else "no"
            out.append(f"| {method.upper()} | `{path}` | {_cell(op.get('summary', ''))} | {_cell(req)} | {resp} | {key} |")
    out += ["", "## Schemas", ""]
    for name, sch in sorted((spec.get("components") or {}).get("schemas", {}).items()):
        out += [f"### {name}", ""]
        if sch.get("description"):
            out += [_cell(sch["description"]), ""]
        props = sch.get("properties") or {}
        if not props:
            out += [f"Type: {_cell(sch.get('type', ''))}" + (f", one of {', '.join(map(str, sch['enum']))}" if sch.get("enum") else ""), ""]
            continue
        req = set(sch.get("required") or [])
        out += ["| Field | Type | Required | Notes |", "|---|---|---|---|"]
        for f, v in props.items():
            t = _schema_ref(v) or ("one of " + ", ".join(map(str, v["enum"])) if v.get("enum") else "")
            if not t and "const" in v:
                t = f"const {v['const']}"
            notes = []
            if v.get("description"):
                notes.append(v["description"])
            for k in ("minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "default"):
                if k in v:
                    notes.append(f"{k} {json.dumps(v[k])}")
            for x in v.get("anyOf") or []:
                for k in ("maxLength", "minLength", "maxItems", "minimum", "maximum"):
                    if k in x:
                        notes.append(f"{k} {json.dumps(x[k])}")
            out.append(f"| `{f}` | {_cell(t)} | {'yes' if f in req else 'no'} | {_cell('; '.join(notes))} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def outputs(root: Path) -> dict[str, str]:
    return {
        "docs/reference/python.md": api.render_python(root),
        "docs/reference/app-lib.md": api.render_app_lib(root),
        "docs/reference/tasks.md": st.render_tasks(root, st.load_lineage(root)),
        "docs/reference/supabase.md": st.render_supabase(root),
        "docs/reference/openapi.md": render_openapi(root),
    }


def main(argv: list[str]) -> int:
    out = outputs(ROOT)
    if "--check" in argv:
        stale = [p for p, t in out.items() if not (ROOT / p).is_file() or (ROOT / p).read_text(encoding="utf-8") != t]
        hard = [p for p in stale if "--strict" in argv or p.rsplit("/", 1)[1] in ("tasks.md", "supabase.md", "openapi.md")]
        for p in stale:
            print(f"{'FAIL' if p in hard else 'note'} {p} is stale; run python -I scripts/docs/build_reference.py")
        if hard:
            return 1
        print(f"reference: ok, {len(out)} generated files match the source")
        return 0
    for p, t in out.items():
        (ROOT / p).write_text(t, encoding="utf-8", newline="\n")
        print(f"reference: wrote {p} ({len(t.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
