#!/usr/bin/env node
/*
 * The prompt registry (T1140, ROADMAP E5): build, check, bump and record.
 *
 *   node scripts/prompts/registry.mjs build              regenerate the bundled JS module (both copies)
 *   node scripts/prompts/registry.mjs check [--base <git ref>] [--no-eval]
 *   node scripts/prompts/registry.mjs check --seed-edit  self-test: an in-place edit must fail
 *   node scripts/prompts/registry.mjs bump <id>          copy v<N>.md to v<N+1>.md and point the registry at it
 *   node scripts/prompts/registry.mjs record <id>        hash the current version, run its eval, write the score
 *
 * What check enforces (exit 1 on any failure):
 *   1. Every registry entry's file exists and parses, and its id and version match the entry.
 *   2. The entry's sha256 is the hash of the file's fragments: text changed without a version
 *      bump fails here ("record" refuses to rehash a version that is already committed).
 *   3. The generated module is what "build" makes from the files, and its two copies are equal.
 *   4. With --base: a prompt file that exists at the base keeps its text (versions are
 *      immutable: a change is a new v<N+1>.md), and an id whose version changed must point at a
 *      new file one version up, carry a score recorded for that version, and pass its eval
 *      through continent-app/scripts/eval/run.mjs --check (offline evals only; --no-eval skips).
 *
 * The registry is prompts/registry.json; the file format is in lib.mjs. Nothing here calls a model.
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fragmentsSha, parseByFormat } from './lib.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const REGISTRY = 'prompts/registry.json';
export const MODULE_COPIES = ['supabase/functions/_shared/prompts.js', 'continent-app/functions/_lib/prompts.js'];
const RUN_MJS = 'continent-app/scripts/eval/run.mjs';

export const readRegistry = (root = ROOT) => JSON.parse(readFileSync(join(root, REGISTRY), 'utf8'));
const writeRegistry = (reg, root = ROOT) => writeFileSync(join(root, REGISTRY), `${JSON.stringify(reg, null, 2)}\n`);

/** The parsed current version of one entry. */
export function loadEntry(id, entry, root = ROOT) {
  const path = join(root, entry.file);
  if (!existsSync(path)) throw new Error(`${id}: ${entry.file} is missing`);
  return parseByFormat(readFileSync(path, 'utf8'), entry.format, { file: entry.file });
}

/** camelCase export name of a prompt id ("plan-day" -> "planDay"). */
export const exportName = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** The text of the bundled module: one export per prompt the app and the Edge Functions use, and the filler. */
export function buildModule(reg, root = ROOT) {
  const parts = [
    '// GENERATED by scripts/prompts/registry.mjs build from prompts/ (T1140, ROADMAP E5). Do not edit.',
    '// Change a prompt by adding prompts/<id>/v<N+1>.md, pointing prompts/registry.json at it,',
    '// then running the build. Two identical copies: supabase/functions/_shared/prompts.js',
    '// (bundled into each Edge Function by supabase functions deploy) and',
    '// continent-app/functions/_lib/prompts.js (Pages Functions and the app). One plain object',
    '// per prompt, so a bundler keeps only the prompts a file imports.',
    '',
    '/** @typedef {{ id: string, version: number, sha256: string, f: Record<string, string> }} Prompt */',
    '',
  ];
  for (const [id, entry] of Object.entries(reg.prompts)) {
    if (entry.runtime !== 'bundle') continue;
    const { frags } = loadEntry(id, entry, root);
    parts.push(`/** @type {Prompt} ${id} v${entry.version} */`);
    parts.push(`export const ${exportName(id)} = {`);
    parts.push(`  id: ${JSON.stringify(id)},`, `  version: ${entry.version},`, `  sha256: ${JSON.stringify(fragmentsSha(frags))},`, '  f: {');
    for (const [name, text] of Object.entries(frags)) parts.push(`    ${JSON.stringify(name)}: ${JSON.stringify(text)},`);
    parts.push('  },', '};', '');
  }
  parts.push(
    '/**',
    ' * One fragment of a prompt with its {{name}} slots filled, in one pass (a value that',
    ' * itself holds "{{x}}" stays as it is). A missing fragment or slot value throws.',
    ' * @param {Prompt} p',
    ' * @param {string} name',
    ' * @param {Record<string, unknown>} [vars]',
    ' * @returns {string}',
    ' */',
    'export function frag(p, name, vars = {}) {',
    '  const t = p.f[name];',
    '  if (t == null) throw new Error(`prompt ${p.id} v${p.version}: no fragment "${name}"`);',
    '  return t.replace(/\\{\\{([A-Za-z_][A-Za-z0-9_]*)\\}\\}/g, (_, k) => {',
    '    if (!(k in vars)) throw new Error(`prompt ${p.id} v${p.version}: fragment "${name}" needs {{${k}}}`);',
    '    return String(vars[k]);',
    '  });',
    '}',
    '',
  );
  return parts.join('\n');
}

const git = (args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'pipe'] });
const gitShow = (ref, path) => { try { return git(['show', `${ref}:${path}`]); } catch { return null; } };

/**
 * The comparison with the base, as data: { failures, bumped }. Pure, so a test can feed it
 * two registries and two file sets. files(side, path) gives a file's text or null.
 */
export function compareWithBase(baseReg, headReg, files) {
  const failures = [];
  const bumped = [];
  const textOf = (side, entry) => {
    const t = files(side, entry.file);
    return t == null ? null : parseByFormat(t, entry.format, { file: entry.file }).frags;
  };
  // Every file the base registry knew, at every version it pointed to: unchanged text.
  for (const [id, b] of Object.entries(baseReg?.prompts || {})) {
    const before = textOf('base', b);
    const after = textOf('head', b);
    if (before && after && fragmentsSha(before) !== fragmentsSha(after)) {
      failures.push(`${id}: ${b.file} (v${b.version}) changed its text; versions are immutable, add v${b.version + 1} instead (node scripts/prompts/registry.mjs bump ${id})`);
    }
    const h = headReg.prompts[id];
    if (!h) { failures.push(`${id}: removed from the registry (retire a prompt in its own task, with its callers)`); continue; }
    if (h.version !== b.version) {
      if (h.version !== b.version + 1) failures.push(`${id}: version ${b.version} to ${h.version}; bump one version at a time`);
      if (h.file === b.file && h.format !== 'trips-header') failures.push(`${id}: v${h.version} must be a new file, not ${b.file}`);
      if (!h.lastScore || h.lastScore.version !== h.version) {
        failures.push(`${id}: v${h.version} has no score recorded for it (node scripts/prompts/registry.mjs record ${id})`);
      }
      bumped.push(id);
    }
  }
  for (const id of Object.keys(headReg.prompts)) if (!baseReg?.prompts?.[id]) bumped.push(id);
  return { failures, bumped };
}

/** Checks 1 to 3 on a tree. */
export function checkTree(root = ROOT) {
  const failures = [];
  const reg = readRegistry(root);
  for (const [id, entry] of Object.entries(reg.prompts)) {
    let parsed;
    try { parsed = loadEntry(id, entry, root); } catch (e) { failures.push(String(e.message)); continue; }
    if (entry.format !== 'trips-header' && parsed.meta.id !== id) failures.push(`${id}: ${entry.file} says id ${parsed.meta.id}`);
    if (parsed.meta.version !== entry.version) failures.push(`${id}: ${entry.file} says version ${parsed.meta.version}, the registry ${entry.version}`);
    const sha = fragmentsSha(parsed.frags);
    if (sha !== entry.sha256) failures.push(`${id}: the text of ${entry.file} changed without a version bump (hash ${sha.slice(0, 12)}, registry ${String(entry.sha256).slice(0, 12)})`);
  }
  let mod = null;
  try { mod = buildModule(reg, root); } catch (e) { failures.push(String(e.message)); }
  for (const copy of MODULE_COPIES) {
    const p = join(root, copy);
    if (!existsSync(p)) failures.push(`${copy} is missing (node scripts/prompts/registry.mjs build)`);
    else if (mod != null && readFileSync(p, 'utf8') !== mod) failures.push(`${copy} is not what the prompt files build (node scripts/prompts/registry.mjs build)`);
  }
  return { failures, reg };
}

function runEval(name) {
  const r = spawnSync(process.execPath, [join(ROOT, RUN_MJS), name, '--check', '--json'], { cwd: join(ROOT, 'continent-app'), encoding: 'utf8', maxBuffer: 64 << 20, env: { ...process.env, CARTA_EVAL_OUT: mkdtempSync(join(tmpdir(), 'carta-prompt-eval-')) } });
  let result = null;
  // --json prints the results array, then the runner's verdict line.
  const a = r.stdout.indexOf('[');
  const b = r.stdout.lastIndexOf('\n]');
  try { result = JSON.parse(r.stdout.slice(a, b + 2)).find((x) => x.eval === name) || null; } catch { /* nothing to read */ }
  return { code: r.status, result, out: `${r.stdout}${r.stderr}`.trim() };
}

function check({ base, evals = true, root = ROOT, quiet = false }) {
  const { failures, reg } = checkTree(root);
  let bumped = [];
  if (base) {
    const baseRegText = gitShow(base, REGISTRY);
    const baseReg = baseRegText ? JSON.parse(baseRegText) : null;
    const cmp = compareWithBase(baseReg, reg, (side, path) => {
      if (side === 'base') return gitShow(base, path);
      const p = join(root, path);
      return existsSync(p) ? readFileSync(p, 'utf8') : null;
    });
    failures.push(...cmp.failures);
    bumped = cmp.bumped;
  }
  const ran = new Map(); // one run per eval, however many of its prompts moved
  for (const id of bumped) {
    const e = reg.prompts[id];
    if (!e.eval) { if (!quiet) console.log(`prompt ${id} v${e.version}: new or bumped; no run.mjs eval guards it (${e.guard || 'none'})`); continue; }
    if (!evals) { console.log(`prompt ${id} v${e.version}: eval ${e.eval} skipped (--no-eval)`); continue; }
    if (!ran.has(e.eval)) ran.set(e.eval, runEval(e.eval));
    const r = ran.get(e.eval);
    console.log(`prompt ${id} v${e.version}: eval ${e.eval} ${r.code === 0 ? 'pass' : `FAIL (exit ${r.code})`}`);
    if (r.code !== 0) failures.push(`${id}: its eval ${e.eval} failed after the bump:\n${r.out.slice(-1500)}`);
  }
  for (const f of failures) console.log(`  - ${f}`);
  const n = Object.keys(reg.prompts).length;
  console.log(failures.length ? `prompt registry: FAIL (${failures.length})` : `prompt registry: OK (${n} prompts${base ? `, against ${base}` : ''})`);
  return failures.length ? 1 : 0;
}

/** Self-test: copy the registry tree, edit one fragment of a committed version in place, check must fail. */
function seedEdit() {
  const tmp = mkdtempSync(join(tmpdir(), 'carta-prompt-seed-'));
  const reg = readRegistry();
  cpSync(join(ROOT, 'prompts'), join(tmp, 'prompts'), { recursive: true });
  for (const copy of MODULE_COPIES) { cpSync(dirname(join(ROOT, copy)), dirname(join(tmp, copy)), { recursive: true }); }
  for (const e of Object.values(reg.prompts)) if (e.format === 'trips-header') { cpSync(join(ROOT, e.file), join(tmp, e.file)); }
  const target = reg.prompts['plan-day'];
  const p = join(tmp, target.file);
  const text = readFileSync(p, 'utf8');
  const edited = text.replace('be finished by 18:00.', 'be finished by 19:00.');
  if (edited === text) { console.error('seed edit: the sentence to edit is gone; update seedEdit()'); return 2; }
  writeFileSync(p, edited);
  console.log(`seed edit: plan-day ${target.file} "finished by 18:00" -> "19:00", version not bumped`);
  return check({ root: tmp, evals: false });
}

function bump(id) {
  const reg = readRegistry();
  const e = reg.prompts[id];
  if (!e) throw new Error(`no prompt ${id}`);
  if (e.format === 'trips-header') throw new Error(`${id} is a Trips generator prompt: raise "version:" in ${e.file} itself (the golden set rebaselines it)`);
  const next = e.version + 1;
  const file = e.file.replace(/v\d+\.md$/, `v${next}.md`);
  if (existsSync(join(ROOT, file))) throw new Error(`${file} exists`);
  const text = readFileSync(join(ROOT, e.file), 'utf8')
    .replace(/^version: \d+$/m, `version: ${next}`)
    .replace(/^(# .*), version \d+$/m, `$1, version ${next}`)
    .replace(/^## Changelog\n\n/m, `## Changelog\n\n- v${next} (T????, date): what changed and why.\n`);
  writeFileSync(join(ROOT, file), text);
  reg.prompts[id] = { ...e, version: next, file };
  writeRegistry(reg);
  console.log(`${file} written; edit its fragments and changelog, then: node scripts/prompts/registry.mjs record ${id} && node scripts/prompts/registry.mjs build`);
}

function record(id) {
  const reg = readRegistry();
  const e = reg.prompts[id];
  if (!e) throw new Error(`no prompt ${id}`);
  const { meta, frags } = loadEntry(id, e);
  if (meta.version !== e.version) throw new Error(`${e.file} says version ${meta.version}, the registry ${e.version}`);
  const committed = gitShow('HEAD', e.file);
  const committedSha = committed ? fragmentsSha(parseByFormat(committed, e.format, { file: e.file }).frags) : null;
  const sha = fragmentsSha(frags);
  if (committedSha && committedSha !== sha) throw new Error(`${e.file} is committed with other text: versions are immutable, run bump ${id} first`);
  e.sha256 = sha;
  if (e.eval) {
    const r = runEval(e.eval);
    if (r.code !== 0) { writeRegistry(reg); throw new Error(`eval ${e.eval} failed (exit ${r.code}); hash written, score not:\n${r.out.slice(-1500)}`); }
    // scoreKey picks one of the eval's metrics (the judge prompt is scored by its kappa); else the headline.
    const h = r.result?.headline || {};
    const key = e.scoreKey || h.key || null;
    const value = e.scoreKey ? (r.result?.metrics?.[e.scoreKey] ?? null) : (h.value ?? null);
    e.lastScore = { version: e.version, eval: e.eval, status: r.result?.status || 'pass', key, value, at: r.result?.at || new Date().toISOString() };
  } else {
    e.lastScore = { version: e.version, eval: null, status: 'unguarded', key: null, value: null, at: new Date().toISOString() };
  }
  writeRegistry(reg);
  console.log(`${id} v${e.version}: sha ${sha.slice(0, 12)}, score ${JSON.stringify(e.lastScore)}`);
}

function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const arg = (n) => { const i = rest.indexOf(n); return i >= 0 ? rest[i + 1] : null; };
  if (cmd === 'build') {
    const mod = buildModule(readRegistry());
    for (const copy of MODULE_COPIES) writeFileSync(join(ROOT, copy), mod);
    console.log(`${MODULE_COPIES.join(' and ')} written`);
    return 0;
  }
  if (cmd === 'check') return rest.includes('--seed-edit') ? seedEdit() : check({ base: arg('--base'), evals: !rest.includes('--no-eval') });
  if (cmd === 'bump') { bump(rest[0]); return 0; }
  if (cmd === 'record') { record(rest[0]); return 0; }
  console.error('usage: registry.mjs build | check [--base <ref>] [--no-eval] [--seed-edit] | bump <id> | record <id>');
  return 2;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(); } catch (e) { console.error(String(e.message)); process.exitCode = 2; }
}
