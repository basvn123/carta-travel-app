"""Writes continent-app/src/components/BrandMarks.jsx from the signed-off logo kit
(continent-app/brand/viantra/svg), so the app's wordmark slot draws the exact paths. K1, decision 0018."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, "continent-app", "brand", "viantra", "svg")
OUT = os.path.join(ROOT, "continent-app", "src", "components", "BrandMarks.jsx")

word = open(os.path.join(KIT, "viantra-wordmark.svg"), encoding="utf-8").read()
vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', word)
W, H = float(vb.group(1)), float(vb.group(2))
outer = re.search(r'<g transform="translate\(([\d.]+) ([\d.]+)\)">', word)
ox, oy = float(outer.group(1)), float(outer.group(2))
glyphs = re.findall(r'<path transform="translate\(([\d.]+) 0\) scale\(([\d.]+) (-[\d.]+)\)" d="([^"]+)"/>', word)
cap = oy - 24          # the generator placed the baseline at 24 + cap height
mark = open(os.path.join(KIT, "viantra-mark.svg"), encoding="utf-8").read()
mark_d = re.search(r' d="([^"]+)"', mark).group(1)

rows = ",\n".join(f"  ['{float(x) + ox:.2f}', '{s}', '{sy}', '{d}']" for x, s, sy, d in glyphs)
jsx = f"""/* The Viantra logo for the app's wordmark slot (ROADMAP K1, decision 0018, signed off 2026-11-26).
   Generated by scripts/gen_brand_component.py from continent-app/brand/viantra/svg; edit the kit, not this file.
   BrandMark: the arch whose opening is a V ("the way through"), terracotta.
   BrandWordmark: "Viantra" in Fraunces (SIL OFL 1.1), outlined, hand-spaced; it takes the text colour and
   is sized by font-size (1em tall caps), so the header's existing size and hide rules keep working. */

const GLYPHS = [
{rows},
];

export function BrandMark({{ className = '', title = 'Viantra' }}) {{
  return (
    <svg className={{className}} viewBox="96 64 320 384" role="img" aria-label={{title}} focusable="false">
      <path fill="var(--brand-mark)" fillRule="evenodd" d="{mark_d}" />
    </svg>
  );
}}

export function BrandWordmark({{ className = '', title = 'Viantra' }}) {{
  return (
    <svg
      className={{`brand-wordmark ${{className}}`.trim()}}
      viewBox="0 {-cap - 4:.1f} {W:.1f} {cap + 8:.1f}"
      role="img"
      aria-label={{title}}
      focusable="false"
      style={{{{ height: '1em', width: 'auto', verticalAlign: '-0.08em', overflow: 'visible' }}}}
    >
      <g fill="currentColor">
        {{GLYPHS.map(([x, s, sy, d]) => (
          <path key={{x}} transform={{`translate(${{x}} 0) scale(${{s}} ${{sy}})`}} d={{d}} />
        ))}}
      </g>
    </svg>
  );
}}
"""
open(OUT, "w", encoding="utf-8", newline="\n").write(jsx)
print("wrote", OUT, len(jsx), "bytes,", len(glyphs), "glyphs")
