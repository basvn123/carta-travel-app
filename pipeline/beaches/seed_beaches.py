"""The famous beaches the famous coverage report found missing from the wire.

Tier: Scheduled (run_pipeline task beaches)

Unlike lakes and mountains there is no hand seed here: every entry is
generated by `pipeline/famous/coverage.py --handoff` (D25 c) into
data/famous/seed_beaches.json, keyed by Wikidata id, why "famous". The
harvest pins each one into its country's rows, the enrich stage always
shortlists it, and the export never leaves it out (it ships rated when it
passes every gate, else as a listed row).

Fields of an entry
    n       the reference name, used only in reports and the seed mark
    cc      ISO2, the country the entry is published under
    wd      the Wikidata id; the harvest matches and fetches by it alone
    why     always "famous"
    lat/lon the reference coordinate, a hint only: the coordinate that ships
            is Wikidata's
    note    why the entry is here, never shipped
"""

import json
from pathlib import Path

FAMOUS_FILE = (Path(__file__).resolve().parents[2]
               / "data" / "famous" / "seed_beaches.json")


def famous_entries(path=None):
    """Generated seed entries, or [] when the file is absent or broken.

    An entry without a Wikidata id or a country is skipped: the harvest
    matches by id only, so it could never resolve."""
    try:
        rows = json.loads(Path(path or FAMOUS_FILE).read_text(
            encoding="utf-8"))["rows"]
    except (OSError, ValueError, KeyError, TypeError):
        return []
    return [r for r in rows if isinstance(r, dict) and r.get("wd")
            and r.get("cc")]


def by_country(path=None):
    """{cc: [entry, ...]} in file order."""
    out = {}
    for row in famous_entries(path):
        out.setdefault(row["cc"], []).append(row)
    return out


if __name__ == "__main__":
    groups = by_country()
    print(f"{sum(len(v) for v in groups.values())} famous beach seeds "
          f"across {len(groups)} countries")
    for cc in sorted(groups):
        print(f"  {cc}: {len(groups[cc])}")
