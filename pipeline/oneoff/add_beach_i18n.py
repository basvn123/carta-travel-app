CATALOGS = {"en": EN, "nl": NL, "de": DE, "fr": FR, "es": ES, "it": IT}


def block(pairs):
    lines = [f"  {MARK_START}", HEAD]
    for key, value in pairs.items():
        text = value.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{key}': '{text}',")
    lines.append(f"  {MARK_END}")
    return "\n".join(lines)


def main():
    for lang, pairs in CATALOGS.items():
        path = I18N / f"{lang}.js"
        source = io.open(path, encoding="utf-8").read()
        new_block = block(pairs)
        if MARK_START in source:
            source = re.sub(
                re.escape(MARK_START).join([r"\s*  ", ""]) + r".*?"
                + re.escape(MARK_END), "", source, flags=re.S)
            source = re.sub(r"\n\s*" + re.escape(MARK_START) + r".*?"
                            + re.escape(MARK_END), "", source, flags=re.S)
        # Insert before the catalogue's closing brace.
        idx = source.rstrip().rfind("};")
        if idx < 0:
            raise SystemExit(f"{path.name}: no closing brace found")
        source = source[:idx] + "\n" + new_block + "\n" + source[idx:]
        io.open(path, "w", encoding="utf-8", newline="\n").write(source)
        print(f"  {lang}: {len(pairs)} beach keys")


if __name__ == "__main__":
    main()
