# Countries with no inland water body worth publishing. Written down rather
# than left to an empty result, so the difference between "we found nothing"
# and "there is nothing" is a fact in the repo rather than a guess in a review.
NO_WATER = {
    "MC": "Monaco has no lake, river or lagoon within its two square kilometres",
}


def by_country():
    """{cc: [entry, ...]} in file order, which is the order a tie breaks in."""
    out = {}
    for row in SEED:
        out.setdefault(row["cc"], []).append(row)
    return out


def countries():
    return sorted({row["cc"] for row in SEED})


if __name__ == "__main__":
    groups = by_country()
    print(f"{len(SEED)} seeded water bodies across {len(groups)} countries")
    for cc in sorted(groups):
        rows = groups[cc]
        bans = sum(1 for r in rows if r.get("swim") == "no")
        brief = sum(1 for r in rows if r.get("why") == "brief")
        print(f"  {cc}: {len(rows):>2}  ({brief} from the brief, {bans} no-swim)")
    for cc, why in sorted(NO_WATER.items()):
        print(f"  {cc}: none by design ({why})")
