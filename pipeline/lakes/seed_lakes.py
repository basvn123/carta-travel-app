"""The curated seed: the water bodies a European traveller has actually heard of.

Everything else in this layer is machine found. This file is the one place a
human decides, and it exists for three reasons the open data cannot cover on
its own.

  fame that no field carries.  Sitelinks and pageviews find Lake Garda. They
        do not reliably find Lago di Sorapis, Rummu quarry, Sorvagsvatn or the
        Blue Eye, which are on every travel blog and every second Instagram
        grid and which Wikidata records as small, ordinary items. A ranking
        that misses those is wrong in the way a traveller notices first.
  every country gets an answer.  The gate in export_lakes.py would otherwise
        publish thirty Alpine lakes and nothing for Malta, Moldova or the
        Faroes. Each seeded entry is pinned into its country's list, so a
        country with four honest water bodies shows four rather than none.
  swimming permission is safety critical.  Plitvice, Morskie Oko, Strbske
        pleso, Skradinski Buk, Loch Katrine and most drinking water reservoirs
        forbid swimming, and several of them are on exactly the lists that
        call them beautiful. `swim` here OVERRIDES every machine signal,
        because a wrong "yes" is the only field in this layer that can hurt
        somebody.

Fields
    n       the searchable name, English where an English name is in use
    alt     other names to match on: the local name, the name on the signpost
    cc      ISO2, the country the entry is published under
    kind    lake | reservoir | lagoon | tarn | crater | river | geothermal
    swim    yes | limited | no | "" (unknown, the machine decides)
              yes      swimming is normal and lawful here
              limited  lawful only in a designated part, or in season, or the
                       famous part of it is closed, or the rule could not be
                       confirmed and the honest answer is "check locally"
              no       forbidden, or physically not a swimming place
    lat/lon approximate, ONLY a disambiguation hint for the resolver. Never
            published: the coordinate that ships is Wikidata's or OSM's.
    wd      an explicit Wikidata id, for the few entries entity search cannot
            reach on any query string. Use it sparingly and only after
            checking the item is the right one.
    why     brief     named in the research brief this layer was built from
            editorial added here because it is what blogs and Instagram name
    haz     curated hazards, merged with whatever the machine finds
    note    why this entry is here, for the next person reading the file.
            Internal. It is never shipped, and no sentence in the app is
            written from it.

Where a rule could not be confirmed the entry says "limited" and the app says
"check the local rules", which is both the honest answer and the safe one.

ASCII clean, no em dashes, per project convention.
"""

